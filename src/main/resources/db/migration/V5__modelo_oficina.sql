DROP TABLE IF EXISTS veiculo;
DROP TABLE IF EXISTS cliente;
DROP TABLE IF EXISTS servico;

CREATE TABLE usuarios (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    email      VARCHAR(100) NOT NULL UNIQUE,
    telefone   VARCHAR(20)  NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil     VARCHAR(20)  NOT NULL,
    criado_em  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE clientes (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER     NOT NULL UNIQUE,
    cpf_cnpj   VARCHAR(20) NOT NULL UNIQUE,
    CONSTRAINT fk_cliente_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE TABLE veiculos (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    INTEGER     NOT NULL,
    placa         VARCHAR(10) NOT NULL UNIQUE,
    marca         VARCHAR(50) NOT NULL,
    modelo        VARCHAR(50) NOT NULL,
    ano           INTEGER     NOT NULL,
    cor           VARCHAR(30),
    chassi        VARCHAR(30) UNIQUE,
    quilometragem INTEGER,
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE RESTRICT
);

CREATE TABLE ordens_servico (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id          INTEGER     NOT NULL,
    cliente_id          INTEGER     NOT NULL,
    status              VARCHAR(30) NOT NULL,
    descricao_problema  TEXT,
    diagnostico_tecnico TEXT,
    valor_total         NUMERIC(10, 2) DEFAULT 0.00,
    data_abertura       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    data_conclusao      TIMESTAMP WITH TIME ZONE NULL DEFAULT NULL,
    CONSTRAINT fk_os_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_os_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE RESTRICT
);

CREATE TABLE pecas_insumos (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                VARCHAR(50)    NOT NULL UNIQUE,
    nome               VARCHAR(100)   NOT NULL,
    unidade_medida     VARCHAR(10)    NOT NULL,
    preco_custo        NUMERIC(10, 2) NOT NULL,
    preco_venda        NUMERIC(10, 2) NOT NULL,
    quantidade_estoque NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    estoque_minimo     NUMERIC(10, 2) NOT NULL DEFAULT 0.00
);

CREATE TABLE ordem_servico_pecas_insumos (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id INTEGER        NOT NULL,
    peca_insumo_id   INTEGER        NOT NULL,
    quantidade       NUMERIC(10, 2) NOT NULL,
    preco_unitario   NUMERIC(10, 2) NOT NULL,
    subtotal         NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_ospi_os FOREIGN KEY (ordem_servico_id) REFERENCES ordens_servico (id) ON DELETE CASCADE,
    CONSTRAINT fk_ospi_peca FOREIGN KEY (peca_insumo_id) REFERENCES pecas_insumos (id) ON DELETE RESTRICT
);

CREATE TABLE servicos (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100)   NOT NULL,
    descricao  TEXT,
    preco_base NUMERIC(10, 2) NOT NULL
);

CREATE TABLE ordem_servico_servicos (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id INTEGER        NOT NULL,
    servico_id       INTEGER        NOT NULL,
    preco_final      NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_oss_os FOREIGN KEY (ordem_servico_id) REFERENCES ordens_servico (id) ON DELETE CASCADE,
    CONSTRAINT fk_oss_servico FOREIGN KEY (servico_id) REFERENCES servicos (id) ON DELETE RESTRICT
);

COMMENT ON TABLE usuarios IS 'Centraliza autenticação e contato de todos';
COMMENT ON COLUMN usuarios.id IS 'Identificador único do usuário';
COMMENT ON COLUMN usuarios.nome IS 'Nome completo (Admin, Mecânico e Cliente)';
COMMENT ON COLUMN usuarios.email IS 'E-mail principal usado para login e autenticação';
COMMENT ON COLUMN usuarios.telefone IS 'Telefone de contato para avisos e emergências';
COMMENT ON COLUMN usuarios.senha_hash IS 'Senha criptografada com algoritmo seguro (BCrypt)';
COMMENT ON COLUMN usuarios.perfil IS 'Papel do usuário no sistema: ADMIN, MECANICO ou CLIENTE';
COMMENT ON COLUMN usuarios.criado_em IS 'Data e hora de registro do usuário';

COMMENT ON TABLE clientes IS 'Perfil de negócio e faturamento';
COMMENT ON COLUMN clientes.id IS 'Identificador único do perfil de cliente';
COMMENT ON COLUMN clientes.usuario_id IS 'Chave estrangeira que vincula o cliente ao seu login (1:1)';
COMMENT ON COLUMN clientes.cpf_cnpj IS 'Documento fiscal obrigatório para faturamento e Ordens de Serviço';

COMMENT ON TABLE veiculos IS 'Veículos dos clientes';
COMMENT ON COLUMN veiculos.id IS 'Identificador único do veículo';
COMMENT ON COLUMN veiculos.cliente_id IS 'Chave estrangeira apontando para o dono do veículo';
COMMENT ON COLUMN veiculos.placa IS 'Placa de identificação oficial do veículo';
COMMENT ON COLUMN veiculos.marca IS 'Montadora (Ex: Fiat, Chevrolet, Volkswagen)';
COMMENT ON COLUMN veiculos.modelo IS 'Modelo do carro (Ex: Onix, Gol, Corolla)';
COMMENT ON COLUMN veiculos.ano IS 'Ano de fabricação';
COMMENT ON COLUMN veiculos.cor IS 'Cor predominante para fácil identificação no pátio';
COMMENT ON COLUMN veiculos.chassi IS 'Número de identificação única do chassi (VIN)';
COMMENT ON COLUMN veiculos.quilometragem IS 'Quilometragem atual registrada do veículo';

COMMENT ON TABLE ordens_servico IS 'Ordens de Serviço (OS)';
COMMENT ON COLUMN ordens_servico.id IS 'Identificador único da Ordem de Serviço';
COMMENT ON COLUMN ordens_servico.veiculo_id IS 'Veículo que está recebendo a manutenção';
COMMENT ON COLUMN ordens_servico.cliente_id IS 'Cliente dono do veículo solicitante da OS';
COMMENT ON COLUMN ordens_servico.status IS 'Situação atual: ABERTA, EM_ANDAMENTO, CONCLUIDA, ENTREGUE';
COMMENT ON COLUMN ordens_servico.descricao_problema IS 'Relato inicial do problema relatado pelo cliente';
COMMENT ON COLUMN ordens_servico.diagnostico_tecnico IS 'Laudo detalhado feito pelo mecânico responsável';
COMMENT ON COLUMN ordens_servico.valor_total IS 'Soma total dos valores de peças/insumos e serviços da OS';
COMMENT ON COLUMN ordens_servico.data_abertura IS 'Data e hora em que a OS foi aberta';
COMMENT ON COLUMN ordens_servico.data_conclusao IS 'Data e hora em que o serviço foi finalizado';

COMMENT ON TABLE pecas_insumos IS 'Peças e insumos (estoque)';
COMMENT ON COLUMN pecas_insumos.id IS 'Identificador único da peça ou insumo';
COMMENT ON COLUMN pecas_insumos.sku IS 'Código de barras ou código de referência interna';
COMMENT ON COLUMN pecas_insumos.nome IS 'Nome do item (Ex: Filtro de Óleo / Óleo 5W30)';
COMMENT ON COLUMN pecas_insumos.unidade_medida IS 'Forma de controle: UN, LT, KG, etc.';
COMMENT ON COLUMN pecas_insumos.preco_custo IS 'Preço pago ao fornecedor na aquisição';
COMMENT ON COLUMN pecas_insumos.preco_venda IS 'Preço cobrado do cliente na Ordem de Serviço';
COMMENT ON COLUMN pecas_insumos.quantidade_estoque IS 'Quantidade atual (suporta decimais para litros/fracionados)';
COMMENT ON COLUMN pecas_insumos.estoque_minimo IS 'Limite mínimo para alertas de recompra';

COMMENT ON TABLE ordem_servico_pecas_insumos IS 'Itens (peças/insumos) em cada OS';
COMMENT ON COLUMN ordem_servico_pecas_insumos.id IS 'Identificador do item vinculado à OS';
COMMENT ON COLUMN ordem_servico_pecas_insumos.ordem_servico_id IS 'Ordem de serviço de destino';
COMMENT ON COLUMN ordem_servico_pecas_insumos.peca_insumo_id IS 'Peça ou insumo utilizado no serviço';
COMMENT ON COLUMN ordem_servico_pecas_insumos.quantidade IS 'Quantidade gasta (permite frações, ex: 1.5 litros)';
COMMENT ON COLUMN ordem_servico_pecas_insumos.preco_unitario IS 'Preço unitário cobrado no momento do lançamento';
COMMENT ON COLUMN ordem_servico_pecas_insumos.subtotal IS 'Quantidade multiplicada pelo preço unitário';

COMMENT ON TABLE servicos IS 'Serviços (mão de obra)';
COMMENT ON COLUMN servicos.id IS 'Identificador único do serviço de mão de obra';
COMMENT ON COLUMN servicos.nome IS 'Nome da mão de obra (Ex: Troca de Óleo, Alinhamento)';
COMMENT ON COLUMN servicos.descricao IS 'Explicação detalhada do que o serviço inclui';
COMMENT ON COLUMN servicos.preco_base IS 'Preço de tabela sugerido para o serviço';

COMMENT ON TABLE ordem_servico_servicos IS 'Serviços (mão de obra) executados em cada OS';
COMMENT ON COLUMN ordem_servico_servicos.id IS 'Identificador do serviço executado na OS';
COMMENT ON COLUMN ordem_servico_servicos.ordem_servico_id IS 'Ordem de serviço de destino';
COMMENT ON COLUMN ordem_servico_servicos.servico_id IS 'Serviço de mão de obra realizado';
COMMENT ON COLUMN ordem_servico_servicos.preco_final IS 'Preço cobrado pelo serviço nesta OS específica';
