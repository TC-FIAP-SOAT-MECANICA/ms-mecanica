CREATE TABLE tb_funcionarios (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE,
    ativo      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_funcionario_usuario FOREIGN KEY (usuario_id) REFERENCES tb_usuarios (id) ON DELETE CASCADE
);

INSERT INTO tb_funcionarios (usuario_id, ativo)
SELECT id, TRUE FROM tb_usuarios WHERE perfil IN ('ADMIN', 'MECANICO');

ALTER TABLE tb_ordens_servico ADD COLUMN mecanico_id INTEGER;
ALTER TABLE tb_ordens_servico ADD COLUMN agendamento_diagnostico TIMESTAMP WITH TIME ZONE;
ALTER TABLE tb_ordens_servico ADD COLUMN status_aprovacao_rejeicao VARCHAR(20);
ALTER TABLE tb_ordens_servico ADD COLUMN data_aprovacao_rejeicao TIMESTAMP WITH TIME ZONE;
ALTER TABLE tb_ordens_servico ADD COLUMN agendamento_servico TIMESTAMP WITH TIME ZONE;
ALTER TABLE tb_ordens_servico ADD CONSTRAINT fk_os_mecanico
    FOREIGN KEY (mecanico_id) REFERENCES tb_funcionarios (id) ON DELETE RESTRICT;

UPDATE tb_ordens_servico SET status = 'RECEBIDA' WHERE status = 'ABERTA';
UPDATE tb_ordens_servico SET status = 'EM_EXECUCAO', status_aprovacao_rejeicao = 'APROVADO'
WHERE status = 'EM_ANDAMENTO';
UPDATE tb_ordens_servico SET status = 'FINALIZADA', status_aprovacao_rejeicao = 'APROVADO'
WHERE status = 'CONCLUIDA';
UPDATE tb_ordens_servico SET status_aprovacao_rejeicao = 'APROVADO' WHERE status = 'ENTREGUE';

COMMENT ON TABLE tb_funcionarios IS 'Funcionários da oficina (perfis ADMIN e MECANICO)';
COMMENT ON COLUMN tb_funcionarios.id IS 'Identificador único do funcionário';
COMMENT ON COLUMN tb_funcionarios.usuario_id IS 'Chave estrangeira que vincula o funcionário ao seu login (1:1)';
COMMENT ON COLUMN tb_funcionarios.ativo IS 'Indica se o funcionário pode ser atribuído a novas OS';

COMMENT ON COLUMN tb_ordens_servico.status IS
    'Situação atual: RECEBIDA, EM_DIAGNOSTICO, AGUARDANDO_APROVACAO, EM_EXECUCAO, FINALIZADA, ENTREGUE';
COMMENT ON COLUMN tb_ordens_servico.mecanico_id IS 'Funcionário (mecânico) que atende a OS';
COMMENT ON COLUMN tb_ordens_servico.agendamento_diagnostico IS 'Data e hora agendadas para o diagnóstico';
COMMENT ON COLUMN tb_ordens_servico.status_aprovacao_rejeicao IS 'Decisão do cliente sobre o orçamento: APROVADO ou REJEITADO';
COMMENT ON COLUMN tb_ordens_servico.data_aprovacao_rejeicao IS 'Data e hora em que o orçamento foi aprovado ou rejeitado';
COMMENT ON COLUMN tb_ordens_servico.agendamento_servico IS 'Data e hora agendadas para a execução do serviço';
